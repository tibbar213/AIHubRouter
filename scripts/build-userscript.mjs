import {readFile,writeFile,mkdir} from 'node:fs/promises';
const read=p=>readFile(p,'utf8');
const core=(await read('extension/core.js')).replace(/^export /gm,'');
let background=(await read('extension/background.js')).replace(/^import .*\r?\n/,'');
// Reuse the extension engine, replacing only platform plumbing.
const listenerStart=background.indexOf('chrome.runtime.onMessage.addListener');
if(listenerStart<0)throw new Error('Background message boundary changed; review userscript adapter');
background=background.slice(0,listenerStart);
background=background.replace(/function serial\(fn\) \{[^\n]+/,`function serial(fn) { const run=()=>navigator.locks.request(LOCK,fn); const p=queue.then(run,run); queue=p.catch(()=>{}); return p; }`);
const start=background.indexOf('async function connectOpenTab()');
const end=background.indexOf('async function identity(app)',start);
if(start<0||end<start)throw new Error('Background auth boundary changed; review userscript adapter');
background=background.slice(0,start)+`async function connectOpenTab(){ disconnected=false; }\n`+background.slice(end);
// Every request uses the current page session, never a stored credential.
background=background.replace("const {auth}=await chrome.storage.session.get('auth');","const auth=await currentAuth();");
background=background.replaceAll("await api(`/api/v1/keys/${c.keyId}/group`,", "await identity(app);\n          await api(`/api/v1/keys/${c.keyId}/group`,");
// Disconnect persists across reloads/tabs; catalog is the explicit reconnect action.
background=background.replace('async function connectedIdentity(app){','async function connectedIdentity(app){\n  disconnected=await GM.getValue(DISCONNECTED,false);\n  if(disconnected)throw new Error(\'AUTH\');');
background=background.replace("if(message.type==='catalog'){", "if(message.type==='catalog'){\n    await GM.setValue(DISCONNECTED,false);disconnected=false;");
background=background.replace("await chrome.storage.session.remove('auth');for", "await GM.setValue(DISCONNECTED,true);disconnected=true;for");
let html=(await read('extension/options.html')).match(/<body>([\s\S]*)<script type="module"/)[1];
html=html.replace('连接只在本次浏览器会话内保留。重启浏览器后需重新访问平台。','脚本使用当前网站登录会话；至少保留一个 AIHub 标签页。')
 .replace('插件不保存完整 API key；只使用网站登录会话访问 aihub.top。平台页面连接后可以关闭。','不保存完整 API key 或登录令牌。页面关闭后停止；后台标签页、休眠及节能可能延后检查。多个标签页共用锁，不重复改组。请勿同时启用扩展版自动改组。')
 .replace('AIHubRouter 0.3.12','AIHubRouter 油猴版 0.1.2');
const css=(await read('extension/options.css')).replaceAll(':root',':host').replace(/\bbody\{/g,'.panel{');
const options=(await read('extension/options.js')).replace(/^import .*\r?\n/,'');
const runtime=await read('userscript/runtime.js');
const output=`// ==UserScript==
// @name         AIHubRouter 渠道优选
// @namespace    https://github.com/tibbar213/AIHubRouter
// @version      0.1.2
// @description  一个 key 绑定一个模型；默认仅预览，按明确授权自动优选渠道。
// @match        https://aihub.top/*
// @noframes
// @run-at       document-idle
// @grant        GM.getValue
// @grant        GM.setValue
// @grant        GM_registerMenuCommand
// @license      MIT
// ==/UserScript==

// Generated by scripts/build-userscript.mjs from the extension engine and UI.
(()=>{'use strict';
if(location.origin!=='https://aihub.top'||window.top!==window.self)return;
${core}
${runtime}
${background}
mountPanel(${JSON.stringify(html)},${JSON.stringify(css)},document=>{
const window={scrollTo:()=>document.body.scrollTo({top:0})};
${options}
});
startScheduler();
})();
`;
if(process.argv.includes('--check')){
  const existing=await read('userscript/AIHubRouter.user.js');
  if(existing.replaceAll('\r\n','\n')!==output.replaceAll('\r\n','\n'))throw new Error('Userscript bundle is stale. Run npm run build:userscript');
  console.log('Userscript bundle matches current source.');
}else{
  await mkdir('userscript',{recursive:true});
  await writeFile('userscript/AIHubRouter.user.js',output);
  console.log('Built userscript/AIHubRouter.user.js');
}
